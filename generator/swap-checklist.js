#!/usr/bin/env node
/* ============================================================
   SWAP-CHECKLIST — lists every SWAP marker on every story-layout
   page, with the data file and field that changes it.

     node generator/swap-checklist.js      writes docs/SWAP-CHECKLIST.md

   Reads the BUILT pages, so run generate.js first. The field hint is
   the comment the generator writes straight after each opening marker.
   ============================================================ */
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const DATA = JSON.parse(fs.readFileSync(path.join(__dirname, 'communities.json'), 'utf8'));
const CITIES = JSON.parse(fs.readFileSync(path.join(__dirname, 'cities.json'), 'utf8'));
const NAMES = { B: 'The Reveal', C: 'The Villain', D: 'The Near-Miss', E: 'The Approval', F: 'The Dusk Walk' };

const pages = [
  ...CITIES.cities.filter(c => c.storyLayout).map(c => ({ c, rel: c.slug })),
  ...DATA.communities.filter(c => c.storyLayout).map(c => ({ c, rel: `${c.city || DATA.config.outputDir}/${c.slug}` }))
];
const clean = (s) => s.replace(/<!--[\s\S]*?-->/g, '').replace(/<script[\s\S]*?<\/script>/g, '')
  .replace(/<[^>]+>/g, ' ').replace(/&mdash;/g, '—').replace(/&amp;/g, '&').replace(/&[a-z#0-9]+;/g, ' ')
  .replace(/\s+/g, ' ').trim();

let md = `# SWAP Checklist — story-layout placeholders

Generated by \`node generator/swap-checklist.js\` from the built pages. **Do not edit by hand** — re-run it after a build.

Every placeholder on the 13 story-layout pages is fenced in the page HTML:

| Marker | What it fences | Swap it for |
|---|---|---|
| \`<!-- SWAP:CLIENT -->\` | the Gallagher family story (hero chip and story line, near-miss, schemes they ruled out, package, painted steps, timeline, proof, P.S.) | a real local client |
| \`<!-- SWAP:LOCAL -->\` | local-problem copy (the local condition, approval trap, "5 ways it goes wrong", what it buys you) | verified local problems |
| \`<!-- SWAP:FAQ -->\` | the FAQ block | local FAQs (the FAQ schema is built from the same \`faqs[]\`, so it follows automatically) |
| \`<!-- SWAP:VIZCOPY -->\` | the visualizer intro copy shared by ~20 pages, and Step Five's lede | page-specific copy (duplicate-content risk until then) |

**How to change one:** never edit the page's \`index.html\` — the next build erases it. Edit the data file and field named in the row, then run \`node generator/generate.js\`, \`node generator/verify-site.js\` and \`node generator/verify-layouts.js\`.

**The family itself** (name, photo, town, chosen scheme, house photos) is one \`story\` block per page. Every page currently has none, so every page falls back to the Orange County page's family — the Gallaghers. Adding a \`story\` block to a page swaps the family in every CLIENT section on that page at once (see \`generator/README.md\`, "Swapping a page's homeowner"). Copy refers to the family only through tokens ({they}, {their}, {family}, {place}, {chosen}), so most CLIENT copy needs no rewrite — only the lines that describe what that family did.

Markers can nest: a SWAP:CLIENT near-miss card sits inside the SWAP:LOCAL "5 ways" section on Layout D pages.

`;

const summary = [];
for (const { c, rel } of pages) {
  const f = path.join(ROOT, rel, 'index.html');
  if (!fs.existsSync(f)) continue;
  const html = fs.readFileSync(f, 'utf8');
  /* nested markers: scan every opening position, not just non-overlapping matches */
  const rows = [];
  let m;
  const openRe = /<!-- SWAP:([A-Z]+) --><!-- edit: ([^>]*?) -->/g;
  while ((m = openRe.exec(html))) {
    const kind = m[1], hint = m[2];
    const end = html.indexOf(`<!-- /SWAP:${kind} -->`, m.index);
    /* for a nested marker of the same kind, the first close after it is its own */
    const inner = html.slice(m.index + m[0].length, end);
    const h = (inner.match(/<h[1-3][^>]*>([\s\S]*?)<\/h[1-3]>/) || [])[1];
    const lead = clean(h || inner).slice(0, 90);
    const field = hint.split(' › ').slice(2).join(' › ') || hint;
    const file = hint.split(' › ')[0];
    rows.push({ kind, lead, file, field });
  }
  const count = (k) => rows.filter(r => r.kind === k).length;
  summary.push({ rel, layout: c.storyLayout, total: rows.length, CLIENT: count('CLIENT'), LOCAL: count('LOCAL'), FAQ: count('FAQ'), VIZCOPY: count('VIZCOPY') });
  const file = rows[0] ? rows[0].file : '';
  md += `\n## /${rel}/ — Layout ${c.storyLayout} · ${NAMES[c.storyLayout]}\n\nData: \`${file}\`, record \`slug: "${c.slug}"\` · ${rows.length} markers\n\n| # | Marker | Starts with | Field to edit |\n|---|---|---|---|\n`;
  rows.forEach((r, i) => { md += `| ${i + 1} | SWAP:${r.kind} | ${r.lead.replace(/\|/g, '/')} | \`${r.field}\` |\n`; });
}

md += `\n## Totals\n\n| Page | Layout | CLIENT | LOCAL | FAQ | VIZCOPY | Total |\n|---|---|---|---|---|---|---|\n`;
for (const s of summary) md += `| /${s.rel}/ | ${s.layout} | ${s.CLIENT} | ${s.LOCAL} | ${s.FAQ} | ${s.VIZCOPY} | ${s.total} |\n`;

fs.writeFileSync(path.join(ROOT, 'docs', 'SWAP-CHECKLIST.md'), md, 'utf8');
console.log(summary.map(s => `${s.rel} [${s.layout}] ${s.total}`).join('\n'));
console.log('\nwrote docs/SWAP-CHECKLIST.md');
